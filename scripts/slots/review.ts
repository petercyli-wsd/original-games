// The slot review's plumbing (docs/SLOTS.md §5, docs/SLOT-EVALUATOR.md), for
// the /review-slot skill. Local and file-based: no API. Claude Code runs the
// three roles (rules card, blind players, designer) in isolated subagents;
// this CLI builds their prompts and computes the overall and the gate in code.
//
//   todo                                    slot games with no review, or a stale one
//   prepare <id...>                         evidence + rules-card prompt (reuses the card if the code is unchanged)
//                                           → .evaluator/slots/<id>/card.md + card.schema.json
//   player-prompt <id...> [--players N] [--more]
//                                           blind player prompts under fresh aliases
//                                           → .evaluator/slots/_blind/<alias>/player.md + player.schema.json;
//                                           --more adds the N plays to the game's current panel
//   play <alias> "<steps>"                  the blind player's only tool (scripts/play.mjs --blind, mapped
//                                           from the alias); helper steps spin, spin×N, turbo, autoplay,
//                                           watch×N, feature (loads with ?feature=1), paytable, close
//   judge-prompt <id...>                    the designer prompt (card + facts + panel + catalogue)
//                                           → .evaluator/slots/<id>/judge.md + review.schema.json
//   score <id...> [--dry-run]               overall, caps and gate in code → games/<id>/src/slot-review.json
//
// SLOT_REVIEW_GAMES_DIR and SLOT_REVIEW_WORK point it at a fixture (dry runs).

import { randomBytes } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { parseArgs } from 'node:util';
import { catalogueEntries, catalogueText, twinsOf } from './review-lib/catalogue';
import { buildEvidence, legacySlotIds, signatureText, slotCodeHash, slotGameIds, srcDir, themeSources, type SlotEvidence } from './review-lib/evidence';
import { bandTable } from './review-lib/facts';
import { mergePanel, panelLabel, panelText, playerProblems } from './review-lib/panel';
import { BLIND, ROOT, WORK } from './review-lib/paths';
import { readPlayLog, runPlay, sessionShortfalls } from './review-lib/play';
import { CARD_SCHEMA, CARD_SYSTEM, cardUser } from './review-lib/prompts/card';
import { JUDGE_SYSTEM, judgeSchema, judgeUser, type DesignerReview } from './review-lib/prompts/judge';
import { PLAYER_SYSTEM, playerSchema, playerUser, type PlayerReview } from './review-lib/prompts/player';
import {
  DESIGNER_KEYS,
  gateReasons,
  medianGrade,
  panelNeeded,
  PANEL_SIZE,
  scoreSlot,
  SLOT_REVIEW_VERSION,
  type Comprehension,
  type DesignerKey,
} from './review-lib/scores';

const { positionals, values } = parseArgs({
  allowPositionals: true,
  options: {
    players: { type: 'string', default: '1' },
    more: { type: 'boolean' },
    'dry-run': { type: 'boolean' },
    json: { type: 'boolean' },
  },
});
const [command, ...ids] = positionals;

function fail(message: string): never {
  console.error(`✗ ${message}`);
  process.exit(1);
}
const rel = (p: string) => {
  const r = relative(ROOT, p).replaceAll('\\', '/');
  return r.startsWith('..') ? p.replaceAll('\\', '/') : r;
};
const write = (path: string, data: unknown) => writeFileSync(path, typeof data === 'string' ? data : `${JSON.stringify(data, null, 2)}\n`);
const readJson = <T>(path: string): T => {
  if (!existsSync(path)) fail(`Missing ${rel(path)}`);
  try {
    return JSON.parse(readFileSync(path, 'utf8')) as T;
  } catch {
    fail(`${rel(path)} is not valid JSON`);
  }
};
const gameDir = (id: string) => {
  const d = join(WORK, id);
  mkdirSync(d, { recursive: true });
  return d;
};
const requireIds = () => (ids.length ? ids : fail(`Usage: npm run slots:review -- ${command} <game-id...>`));
const promptFile = (system: string, user: string, schemaPath: string) =>
  `<!-- Generated by scripts/slots/review.ts. Follow the SYSTEM section as your instructions, then answer the USER section. -->

# SYSTEM

${system}

# USER

${user}

# OUTPUT

Reply with a single JSON object only (no prose, no code fences) that matches the schema in ${schemaPath}.
`;

// ---------------------------------------------------------------------------
// Blind aliases: .evaluator/slots/_blind/<alias>/ holds everything a player
// reads or writes; the alias → id map lives in _blind/_map/<alias>, which the
// player is never told about.
// ---------------------------------------------------------------------------

const aliasFile = (alias: string) => join(BLIND, '_map', alias);
const gameOfAlias = (alias: string) => (existsSync(aliasFile(alias)) ? readFileSync(aliasFile(alias), 'utf8').trim() : undefined);
type PlayerMeta = { aliases: string[]; codeHash: string };
const metaOf = (id: string): PlayerMeta | undefined => (existsSync(join(WORK, id, 'player.meta.json')) ? readJson<PlayerMeta>(join(WORK, id, 'player.meta.json')) : undefined);

/** The panel's player reviews, in alias order; fails if any is missing or invalid. */
function panelReviews(id: string): { aliases: string[]; reviews: PlayerReview[] } {
  const meta = metaOf(id);
  if (!meta?.aliases.length) fail(`${id}: no blind players yet (run player-prompt ${id})`);
  const reviews = meta.aliases.map((a, i) => {
    const f = join(BLIND, a, 'player.json');
    if (!existsSync(f)) fail(`${id}: player ${panelLabel(i)} (${a}) has not written ${rel(f)} yet`);
    const r = readJson<PlayerReview>(f);
    const problems = playerProblems(r);
    if (problems.length) fail(`${rel(f)}: ${problems.join('; ')} (give the error to a fresh player subagent to fix the JSON)`);
    return r;
  });
  return { aliases: meta.aliases, reviews };
}

