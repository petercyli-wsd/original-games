async function todo() {
  const rows: string[] = [];
  for (const id of slotGameIds()) {
    const f = join(srcDir(id), 'slot-review.json');
    if (!existsSync(f)) {
      rows.push(`${id}: never reviewed`);
      continue;
    }
    const r = JSON.parse(readFileSync(f, 'utf8')) as { codeHash?: string; version?: number };
    if (r.codeHash !== slotCodeHash(id)) rows.push(`${id}: stale (code changed since the review)`);
    else if (r.version !== SLOT_REVIEW_VERSION) rows.push(`${id}: stale (reviewed under slot evaluator v${r.version}, now v${SLOT_REVIEW_VERSION})`);
  }
  console.log(`${rows.length} slot game(s) need a review:${rows.length ? `\n${rows.join('\n')}` : ''}`);
}

async function prepare() {
  for (const id of requireIds()) {
    const d = gameDir(id);
    const previous = existsSync(join(d, 'evidence.json')) ? readJson<{ codeHash: string }>(join(d, 'evidence.json')).codeHash : undefined;
    const e = await buildEvidence(id);
    write(join(d, 'evidence.json'), e);
    write(join(d, 'card.schema.json'), CARD_SCHEMA);
    for (const w of e.warnings) console.log(`! ${id}: ${w}`);
    if (e.factsMissing.length) console.log(`! ${id}: slot-facts.json lacks ${e.factsMissing.join(', ')}`);
    if (previous === e.codeHash && existsSync(join(d, 'card.json'))) {
      rmSync(join(d, 'card.md'), { force: true });
      console.log(`✓ ${id}: rules card cached for this code (${e.codeHash}) → ${rel(join(d, 'card.json'))} (skip the card step)`);
      continue;
    }
    rmSync(join(d, 'card.json'), { force: true });
    write(join(d, 'card.md'), promptFile(CARD_SYSTEM, cardUser(e, themeSources(id)), rel(join(d, 'card.schema.json'))));
    console.log(`✓ ${id}: needs a rules card → read ${rel(join(d, 'card.md'))}, write ${rel(join(d, 'card.json'))}`);
  }
}

async function playerPrompt() {
  const n = Math.max(1, Number(values.players) || 1);
  for (const id of requireIds()) {
    if (!existsSync(join(srcDir(id), 'manifest.ts'))) fail(`No game ${id}`);
    const d = gameDir(id);
    const codeHash = slotCodeHash(id);
    const current = values.more ? metaOf(id) : undefined;
    if (current && current.codeHash !== codeHash) fail(`${id}: the code changed since the current panel was played; start a new panel (no --more)`);
    const aliases = [...(current?.aliases ?? [])];
    mkdirSync(join(BLIND, '_map'), { recursive: true });
    for (let i = 0; i < n; i++) {
      const alias = `s-${randomBytes(3).toString('hex')}`;
      const b = join(BLIND, alias);
      mkdirSync(b, { recursive: true });
      write(aliasFile(alias), id);
      write(join(b, 'player.schema.json'), playerSchema());
      write(join(b, 'player.md'), promptFile(PLAYER_SYSTEM, playerUser(alias), rel(join(b, 'player.schema.json'))));
      aliases.push(alias);
      console.log(`✓ ${id}: blind player ${panelLabel(aliases.length - 1)} as ${alias} → read ${rel(join(b, 'player.md'))}, write ${rel(join(b, 'player.json'))}`);
    }
    write(join(d, 'player.meta.json'), { aliases, codeHash } satisfies PlayerMeta);
    // A designer review of an older panel no longer applies.
    for (const f of ['review.json', 'judge.md', 'panel.json']) rmSync(join(d, f), { force: true });
  }
}

async function play() {
  const [alias, steps] = ids;
  if (!alias || !steps) fail('Usage: npm run slots:review -- play <alias> "<steps>"');
  const id = gameOfAlias(alias);
  if (!id) fail(`No player ${alias}`);
  let res;
  try {
    res = runPlay(id, join(BLIND, alias), steps, join(gameDir(id), 'play-errors.log'));
  } catch (err) {
    fail((err as Error).message);
  }
  console.log(res.output);
  if (!res.ok) process.exitCode = 1;
}

/** Up to 10 screenshots from the panel's sessions for the designer's polish score, copied beside judge.md. */
function designerShots(id: string, aliases: string[]): string[] {
  const out = join(gameDir(id), 'shots');
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  const picked: string[] = [];
  const per = Math.max(2, Math.floor(10 / aliases.length));
  aliases.forEach((alias, i) => {
    const ui = join(BLIND, alias, 'ui');
    if (!existsSync(ui)) return;
    const runs = readdirSync(ui).filter((r) => r.startsWith('run-')).sort((a, b) => Number(a.slice(4)) - Number(b.slice(4)));
    const log = readPlayLog(join(BLIND, alias));
    const files = (run: string) => (existsSync(join(ui, run)) ? readdirSync(join(ui, run)).sort() : []);
    const want: [string, string][] = [];
    const first = runs[0] && files(runs[0]).find((f) => /^\d+-.*\.png$/.test(f));
    if (first) want.push([runs[0], first]);
    for (const run of runs) {
      const p = files(run).find((f) => /-paytable(-1)?\.png$/.test(f));
      if (p) {
        want.push([run, p]);
        break;
      }
    }
    const featureRuns = log.filter((e) => e.feature).map((e) => `run-${e.run}`);
    for (const run of featureRuns) for (const f of files(run).filter((f) => /^sheet-\d+\.png$/.test(f))) want.push([run, f]);
    const lastSheetRun = [...runs].reverse().find((r) => !featureRuns.includes(r) && files(r).some((f) => f.startsWith('sheet-')));
    if (lastSheetRun) want.push([lastSheetRun, files(lastSheetRun).filter((f) => f.startsWith('sheet-'))[0]]);
    for (const [run, f] of want.slice(0, per)) {
      const dest = join(out, `${panelLabel(i)}-${run}-${f}`);
      copyFileSync(join(ui, run, f), dest);
      picked.push(rel(dest));
    }
  });
  return picked;
}

async function judgePrompt() {
  for (const id of requireIds()) {
    const d = gameDir(id);
    const card = readJson<Record<string, unknown>>(join(d, 'card.json'));
    const missing = CARD_SCHEMA.required.filter((k) => !(k in card));
    if (missing.length) fail(`${id}: card.json lacks ${missing.join(', ')}; rerun the rules-card step`);
    const e = await buildEvidence(id);
    const prepared = readJson<{ codeHash: string }>(join(d, 'evidence.json'));
    if (prepared.codeHash !== e.codeHash) fail(`${id}: the code changed since prepare; run prepare again (and a fresh panel)`);
    const { aliases, reviews } = panelReviews(id);
    const meta = metaOf(id)!;
    if (meta.codeHash !== e.codeHash) fail(`${id}: the panel played older code; run player-prompt ${id} again`);
    const merged = mergePanel(reviews);
    const shortfalls = aliases.map((a) => sessionShortfalls(readPlayLog(join(BLIND, a))));
    shortfalls.forEach((s, i) => s.length && console.log(`! ${id}: player ${panelLabel(i)} (${aliases[i]}) fell short of the session brief: ${s.join('; ')}`));
    const entries = await catalogueEntries(id);
    const twins = twinsOf(e.signature, entries);
    const user = judgeUser({
      card,
      facts: bandTable(e.bands),
      factsRaw: e.factsRaw,
      signature: signatureText(e.signature),
      twins,
      panel: panelText(reviews, merged, shortfalls),
      catalogue: await catalogueText(id, entries),
      shots: designerShots(id, aliases),
      warnings: e.warnings,
      trademarks: e.trademarks,
    });
    write(join(d, 'panel.json'), merged);
    write(join(d, 'review.schema.json'), judgeSchema(merged.labels));
    write(join(d, 'judge.md'), promptFile(JUDGE_SYSTEM, user, rel(join(d, 'review.schema.json'))));
    write(join(d, 'judge.meta.json'), { aliases, codeHash: e.codeHash, twins });
    rmSync(join(d, 'review.json'), { force: true });
    console.log(`✓ ${id}: designer prompt, panel of ${aliases.length}${twins.length ? `, signature twins: ${twins.join(', ')}` : ''} → read ${rel(join(d, 'judge.md'))}, write ${rel(join(d, 'review.json'))}`);
  }
}

function designerProblems(r: DesignerReview, labels: string[]): string[] {
  const out: string[] = [];
  for (const k of DESIGNER_KEYS) {
    const c = r.criteria?.find((x) => x.key === k);
    if (!c) out.push(`criteria lacks ${k}`);
    else if (![1, 2, 3, 4, 5].includes(c.score)) out.push(`${k} score ${c.score} is not 1–5`);
  }
  for (const l of labels) {
    const g = r.comprehension?.find((x) => x.player === l);
    if (!g) out.push(`comprehension lacks player ${l}`);
    else if (!['correct', 'partial', 'misread'].includes(g.grade)) out.push(`player ${l} grade ${g.grade} is not correct/partial/misread`);
  }
  if (typeof r.verdict !== 'string') out.push('missing verdict');
  if (!Array.isArray(r.trademarks)) out.push('missing trademarks (an array, empty if none)');
  return out;
}

async function score() {
  const rows = [];
  for (const id of requireIds()) {
    const d = gameDir(id);
    const e: SlotEvidence = await buildEvidence(id);
    const jm = readJson<{ aliases: string[]; codeHash: string }>(join(d, 'judge.meta.json'));
    if (jm.codeHash !== e.codeHash) fail(`${id}: the code changed since the review (${jm.codeHash} → ${e.codeHash}); review it again`);
    const { aliases, reviews } = panelReviews(id);
    if (aliases.join() !== jm.aliases.join()) fail(`${id}: the panel changed since judge-prompt; run judge-prompt ${id} and the designer again`);
    const merged = mergePanel(reviews);
    const review = readJson<DesignerReview>(join(d, 'review.json'));
    const problems = designerProblems(review, merged.labels);
    if (problems.length) fail(`${rel(join(d, 'review.json'))}: ${problems.join('; ')} (give the error to a fresh designer subagent to fix the JSON)`);
    const designer = Object.fromEntries(DESIGNER_KEYS.map((k) => [k, review.criteria.find((c) => c.key === k)!.score])) as Record<DesignerKey, number>;
    const grades = merged.labels.map((l) => review.comprehension.find((c) => c.player === l)!.grade as Comprehension);
    const comprehension = medianGrade(grades);
    const scored = scoreSlot({ player: merged.scores, designer, comprehension, wideMisses: e.wideMisses, hasFeature: e.hasFeature });
    const entries = await catalogueEntries(id);
    const known = new Set([...slotGameIds(), ...legacySlotIds()].filter((x) => x !== id));
    const dup = review.duplicate_of?.trim();
    if (dup && !known.has(dup)) console.log(`! ${id}: the designer's duplicate_of "${dup}" is not a catalogue slot; ignored for the gate`);
    const reskinOf = [...new Set([...twinsOf(e.signature, entries), ...(dup && known.has(dup) ? [dup] : [])])];
    const reasons = gateReasons({
      overall: scored.overall,
      scores: scored.scores,
      hasFeature: e.hasFeature,
      oraclePresent: e.oracle.present,
      rtp: e.rtp,
      factFailures: e.factFailures,
      reskinOf,
      players: merged.players,
      trademarks: [...e.trademarks, ...(Array.isArray(review.trademarks) ? review.trademarks.filter((t) => typeof t === 'string' && t.trim()).map((t) => `${t} (designer)`) : [])],
    });
    const shortfalls = aliases.map((a) => sessionShortfalls(readPlayLog(join(BLIND, a))));
    const misreads = review.comprehension.filter((c) => c.grade !== 'correct').map((c) => `Player ${c.player} ${c.grade}: ${c.reasoning}`);
    const out = {
      version: SLOT_REVIEW_VERSION,
      overall: scored.overall,
      scores: scored.scores,
      gate: reasons.length === 0,
      gateReasons: reasons,
      verdict: review.verdict,
      pros: review.pros,
      cons: [
        ...review.cons,
        ...scored.caps.map((c) => `Cap: ${c}`),
        ...(comprehension !== 'correct' ? [`The blind panel's understanding was graded "${comprehension}". ${misreads.join(' ')}`] : []),
      ],
      confusions: merged.confusions,
      players: merged.players,
      codeHash: e.codeHash,
      date: new Date().toISOString().slice(0, 10),
    };
    const detail = {
      ...out,
      mean: scored.mean,
      comprehension,
      grades,
      recommendation: review.recommendation,
      reskinOf,
      rtp: e.rtp,
      rtpSource: e.rtpSource,
      bands: e.bands.map((b) => ({ key: b.key, shown: b.shown, band: b.band, status: b.status })),
      sessionShortfalls: Object.fromEntries(shortfalls.map((s, i) => [panelLabel(i), s])),
      panelSpread: merged.spread,
    };
    write(join(d, 'score.json'), detail);
    if (!values['dry-run']) write(join(srcDir(id), 'slot-review.json'), out);
    rows.push(detail);
    const panelHint = panelNeeded(scored.overall, merged.players) ? `\n  → widen to a panel: npm run slots:review -- player-prompt ${id} --players ${PANEL_SIZE - merged.players} --more` : '';
    const shortHint = shortfalls.some((s) => s.length) ? `\n  ! session shortfalls: ${aliases.map((_, i) => (shortfalls[i].length ? `${panelLabel(i)}: ${shortfalls[i].join(', ')}` : '')).filter(Boolean).join(' | ')}` : '';
    if (!values.json)
      console.log(
        `${out.gate ? 'PASS' : 'FAIL'} ${id} ${out.overall.toFixed(2)} (${Object.entries(out.scores)
          .map(([k, v]) => `${k} ${v}`)
          .join(', ')})${reasons.length ? `: ${reasons.join('; ')}` : ''}${values['dry-run'] ? ' [dry run: slot-review.json not written]' : ` → ${rel(join(srcDir(id), 'slot-review.json'))}`}${scored.caps.length ? `\n  caps: ${scored.caps.join(' | ')}` : ''}${panelHint}${shortHint}`,
      );
  }
  if (values.json) console.log(JSON.stringify(rows, null, 2));
  if (rows.some((r) => !r.gate)) process.exitCode = 1;
}

const commands: Record<string, () => Promise<void>> = {
  todo,
  prepare,
  'player-prompt': playerPrompt,
  play,
  'judge-prompt': judgePrompt,
  score,
};

